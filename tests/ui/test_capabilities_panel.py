"""The capabilities panel: same payload as the CLI, drawn.

These tests never shell out to netsh / iw: the builder is injected. What they guard is the two
things a panel can get wrong beyond layout: showing a different picture than the CLI prints, and
copying something other than what the CLI prints.
"""
from __future__ import annotations

import io

import pytest
from rich.console import Console
from textual.app import App
from textual.widgets import Button

from wifit3 import host_profile
from wifit3 import wireless_capabilities as wc
from wifit3.device import host_radios as hr
from wifit3.ui.app import WifiteApp
from wifit3.ui.screens.capabilities import CapabilitiesPanel
from tests.ui.wait_until import wait_until


def _cnvi() -> hr.HostRadio:
    return hr._classify(hr.HostRadio(vendor=hr.INTEL_VENDOR, device=0xA0F0))


def _profile(*verdicts: wc.Verdict, radios=()) -> host_profile.HostProfile:
    adapters = [wc.AdapterReport(name="WLAN", verdict=verdict, driver="Netwtw10.sys",
                                 driver_version="23.60.1.2")
                for verdict in verdicts]
    for adapter in adapters:
        adapter.capabilities["monitor_mode"] = wc.Capability(
            key="monitor_mode", label="network monitor mode", value=False, raw="monitor: no",
            value_text="no")
    return host_profile.HostProfile(
        platform="win32",
        capabilities=wc.ProbeReport(platform="win32", adapters=adapters,
                                    notes=["WDI exposes no monitor mode"]),
        radios=list(radios),
        drivable_ids=382,
        scanned_at="2026-11-16T15:00:00+08:00",
    )


class _Host(App):
    """Minimal host: push the panel straight in, no device manager."""

    def __init__(self, panel: CapabilitiesPanel) -> None:
        super().__init__()
        self._panel = panel

    def on_mount(self) -> None:
        self.push_screen(self._panel)


def _plain(renderable) -> str:
    buffer = io.StringIO()
    Console(file=buffer, width=110, color_system=None).print(renderable)
    return buffer.getvalue()


# ---- the body ------------------------------------------------------------

async def test_the_probe_result_replaces_the_placeholder():
    panel = CapabilitiesPanel(builder=lambda: _profile(wc.Verdict.FIRMWARE_REFUSED,
                                                       radios=[_cnvi()]))
    app = _Host(panel)
    async with app.run_test(size=(120, 40)) as pilot:
        await wait_until(pilot, lambda: panel.body is not None)
        text = _plain(panel.body)
        assert "firmware_refused" in text
        assert "cnvi" in text
        assert "Probing this host" not in text


async def test_a_failed_probe_is_reported_not_swallowed():
    def boom() -> host_profile.HostProfile:
        raise OSError("netsh is not on PATH")

    panel = CapabilitiesPanel(builder=boom)
    app = _Host(panel)
    async with app.run_test(size=(120, 40)) as pilot:
        await wait_until(pilot, lambda: panel.body is not None)
        text = _plain(panel.body)
        assert "probe failed" in text
        assert "netsh is not on PATH" in text


async def test_refresh_probes_again():
    calls: list[int] = []

    def counting() -> host_profile.HostProfile:
        calls.append(1)
        return _profile(wc.Verdict.PASSIVE_ONLY)

    panel = CapabilitiesPanel(builder=counting)
    app = _Host(panel)
    async with app.run_test(size=(120, 40)) as pilot:
        await wait_until(pilot, lambda: len(calls) == 1)
        await pilot.press("r")
        await wait_until(pilot, lambda: len(calls) == 2)
        assert panel.profile is not None


# ---- the copy action -----------------------------------------------------

async def test_copy_hands_over_exactly_what_the_cli_prints():
    """A pasted report and a screenshot must be the same evidence, so the copy is generated by
    the CLI's own renderer rather than by the panel's tables."""
    profile = _profile(wc.Verdict.FIRMWARE_REFUSED, radios=[_cnvi()])
    copied: list[str] = []
    panel = CapabilitiesPanel(builder=lambda: profile)
    app = _Host(panel)
    app.copy_to_clipboard = lambda text: copied.append(text)  # type: ignore[method-assign]
    async with app.run_test(size=(120, 40)) as pilot:
        await wait_until(pilot, lambda: panel.profile is not None)
        await pilot.press("y")
        await pilot.pause(0)
    assert copied == [host_profile.render_text(profile)]


