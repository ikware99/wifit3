async def test_escape_closes_the_panel():
    panel = CapabilitiesPanel(builder=lambda: _profile(wc.Verdict.PASSIVE_ONLY))
    app = _Host(panel)
    async with app.run_test(size=(120, 40)) as pilot:
        await wait_until(pilot, lambda: panel.profile is not None)
        await pilot.press("escape")
        await pilot.pause(0)
        assert app.screen is not panel


@pytest.mark.parametrize("w,h", [(80, 24), (60, 18), (50, 16)])
async def test_buttons_stay_on_screen_at_small_terminal_sizes(w, h):
    """A 90%-height frame with a docked button row must not push Close off the bottom."""
    panel = CapabilitiesPanel(builder=lambda: _profile(wc.Verdict.FIRMWARE_REFUSED,
                                                       radios=[_cnvi()]))
    app = _Host(panel)
    async with app.run_test(size=(w, h)) as pilot:
        await wait_until(pilot, lambda: panel.body is not None)
        for button_id in ("#btn-refresh", "#btn-copy", "#btn-close"):
            region = panel.query_one(button_id, Button).region
            assert region.width > 0 and region.height > 0, (button_id, region)
            assert region.y >= 0 and region.bottom <= h, (button_id, region, h)
            assert region.x >= 0 and region.right <= w, (button_id, region, w)


# ---- the app-level entry point -------------------------------------------

@pytest.mark.asyncio
@pytest.mark.usefixtures("no_usb_devices")
async def test_ctrl_r_opens_the_panel_without_a_radio(monkeypatch):
    """The panel is reachable on exactly the host that needs it: one with no drivable card."""
    monkeypatch.setattr(host_profile, "build", lambda: _profile(wc.Verdict.FIRMWARE_REFUSED,
                                                                radios=[_cnvi()]))
    app = WifiteApp()
    async with app.run_test() as pilot:
        await pilot.pause(0)
        await pilot.press("ctrl+r")
        await wait_until(pilot, lambda: isinstance(app.screen, CapabilitiesPanel))
        panel = app.screen
        await wait_until(pilot, lambda: panel.profile is not None)
        assert panel.profile.can_inject is False
